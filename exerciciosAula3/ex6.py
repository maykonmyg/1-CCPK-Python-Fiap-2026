numA = int(input("Digite o primeiro numero: "))
numB = int(input("Digite o segundo numero: "))
operador = (input("Digite o operador: "))

if operador == "+":
    print(numA + numB)
elif(operador == "-"):
    print(numA - numB)
elif(operador == "*"):
    print(numA * numB)
if(operador == "/"):
    print(numA / numB)
